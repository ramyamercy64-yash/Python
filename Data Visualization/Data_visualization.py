import seaborn as sns
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
# Load the 'taxis' dataset
df=sns.load_dataset("taxis")
print(df)

df.isnull().sum()

df.columns

df.isnull().sum()

num_cols = df.select_dtypes(include=np.number).columns

for col in num_cols:
    df[col] = df[col].fillna(df[col].median())

cat_cols = df.select_dtypes(include="object").columns

for col in cat_cols:
    if df[col].isnull().sum() > 0:
        df[col] = df[col].fillna(df[col].mode()[0])



df = df.dropna(subset=['pickup', 'fare'])

print(df.isnull().sum())

#★ Line Chart
#Plot a line chart to visualize the fare over time, using the pickup timestamp as the x-axis and fare as the y-axis. Ensure the pickup column is converted to a datetime  format before plotting
# Convert pickup column into datetime

df['pickup'] = pd.to_datetime(df['pickup'])

# Sort data by pickup time
df = df.sort_values('pickup')

# Create line chart
plt.figure(figsize=(12,5))

plt.plot(df['pickup'], df['fare'])

plt.title('Fare Over Time')
plt.xlabel('Pickup Time')
plt.ylabel('Fare Amount')

plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

#★ Bar Chart
#Create a bar chart to show the total fare for each pickup_borough. Group the data by pickup_borough and sum the fare for each group.

borough_fare = df.groupby('pickup_borough')['fare'].sum()

plt.figure(figsize=(8,5))

borough_fare.plot(kind='bar')

plt.title('Total Fare by Pickup Borough')
plt.xlabel('Pickup Borough')
plt.ylabel('Total Fare')

plt.xticks(rotation=45)
plt.show()

#★ Pie Chart
#Plot a pie chart showing the distribution of trips based on the payment method (credit card, cash, etc.). Each slice should represent the count of trips for a specific payment method.

payment_count = df['payment'].value_counts()

plt.figure(figsize=(7,7))

plt.pie(
    payment_count,
    labels=payment_count.index,
    autopct='%1.1f%%',
    startangle=90
)

plt.title('Payment Method Distribution')
plt.show()

#★ Histogram
#Create a histogram to visualize the distribution of distance. Customize the number of bins for better granularity and ensure the plot is easy to interpret.

plt.figure(figsize=(8,5))

plt.hist(df['distance'], bins=20, edgecolor='black')

plt.title('Distribution of Trip Distance')
plt.xlabel('Distance')
plt.ylabel('Number of Trips')

plt.show()

#★ Box Plot

plt.figure(figsize=(10,5))

sns.boxplot(
    data=df,
    x='pickup_borough',
    y='tip'
)

plt.title('Tip Amount by Pickup Borough')
plt.xlabel('Pickup Borough')
plt.ylabel('Tip Amount')

plt.xticks(rotation=45)
plt.show()

#Visualizations using Seaborn:
#★ Count Plot
#Count Plot – Number of Trips by Borough
plt.figure(figsize=(9,5))

sns.countplot(
    data=df,
    x='pickup_borough'
)

plt.title('Number of Trips by Pickup Borough')
plt.xlabel('Pickup Borough')
plt.ylabel('Number of Trips')

plt.xticks(rotation=45)
plt.show()

#★ Scatter Plot
#Scatter Plot – Distance vs Fare

plt.figure(figsize=(10,6))

sns.scatterplot(
    data=df,
    x='distance',
    y='fare',
    hue='pickup_borough'
)

plt.title('Distance vs Fare')
plt.xlabel('Distance')
plt.ylabel('Fare')

plt.show()

#Heatmap – Correlation Between Numerical Variables

corr = df[['distance', 'fare', 'tip', 'tolls', 'total']].corr()

plt.figure(figsize=(8,6))

sns.heatmap(
    corr,
    annot=True,
    cmap='coolwarm',
    fmt='.2f'
)

plt.title('Correlation Heatmap')
plt.show()

#Pair Plot – Pairwise Relationships

sns.pairplot(
    data=df,
    vars=['distance', 'fare', 'tip', 'total'],
    hue='pickup_zone'
)

plt.show()

#Violin Plot – Fare Distribution by Payment Method

plt.figure(figsize=(9,5))

sns.violinplot(
    data=df,
    x='payment',
    y='fare'
)

plt.title('Fare Distribution by Payment Method')
plt.xlabel('Payment Method')
plt.ylabel('Fare Amount')

plt.show()